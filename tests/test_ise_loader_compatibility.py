class TestHashNormalization:
    """Test hash normalization for loader compatibility."""

    def test_normalize_hash_with_prefix(self):
        """Test that SHA256: prefix is properly stripped."""
        hash_with_prefix = "SHA256:a1b2c3d4e5f6"
        normalized = normalize_hash(hash_with_prefix)
        assert normalized == "a1b2c3d4e5f6"

    def test_normalize_hash_without_prefix(self):
        """Test that hash without prefix is returned as-is."""
        hash_without_prefix = "a1b2c3d4e5f6"
        normalized = normalize_hash(hash_without_prefix)
        assert normalized == "a1b2c3d4e5f6"

    def test_normalize_hash_lowercase(self):
        """Test that hash is lowercased."""
        hash_upper = "SHA256:A1B2C3D4E5F6"
        normalized = normalize_hash(hash_upper)
        assert normalized == "a1b2c3d4e5f6"
