class TestISELoaderCompatibility:
    """Test that ISE-generated bundles load in the runtime loader."""

    def setup_method(self):
        """Clear safe mode before each test."""
        runtime_state.set_active()

    def teardown_method(self):
        """Clear safe mode after each test."""
        runtime_state.set_active()

    def test_ise_bundle_manifest_format(self):
        """Test that ISE generates manifest in loader-compatible format."""
        with tempfile.TemporaryDirectory() as tmpdir:
            result = compile_bundle(
                idl=MINIMAL_IDL,
                bundle_name="test-bundle",
                output_dir=tmpdir,
                validate_finance_pilot=True,
            )

            assert result.success, f"Compilation failed: {result.error_message}"

            # Read the generated manifest
            manifest_path = Path(tmpdir) / "test-bundle" / "bundle.manifest.json"
            assert manifest_path.exists()

            with open(manifest_path) as f:
                manifest = json.load(f)

            # Verify loader-compatible format
            assert "name" in manifest, "Manifest should have 'name' field"
            assert "version" in manifest, "Manifest should have 'version' field"
            assert "contracts" in manifest, "Manifest should have 'contracts' field"
            assert isinstance(manifest["contracts"], list), "contracts should be a list"

            # Verify contract entries have required fields
            for contract in manifest["contracts"]:
                assert "file" in contract, "Contract should have 'file' field"
                assert "sha256" in contract, "Contract should have 'sha256' field"
                assert "required" in contract, "Contract should have 'required' field"

    def test_ise_bundle_emits_institutional_contracts(self):
        """Test that ISE emits all mandatory institutional contracts."""
        with tempfile.TemporaryDirectory() as tmpdir:
            result = compile_bundle(
                idl=MINIMAL_IDL,
                bundle_name="test-bundle",
                output_dir=tmpdir,
                validate_finance_pilot=True,
            )

            assert result.success, f"Compilation failed: {result.error_message}"

            bundle_path = Path(tmpdir) / "test-bundle"

            # Verify all mandatory contracts exist
            assert (bundle_path / "policies.json").exists(), "policies.json should exist"
            assert (bundle_path / "mandates.json").exists(), "mandates.json should exist"
            assert (bundle_path / "autonomy.json").exists(), "autonomy.json should exist"

            # Verify they are valid JSON
            for filename in ["policies.json", "mandates.json", "autonomy.json"]:
                with open(bundle_path / filename) as f:
                    data = json.load(f)
                    assert isinstance(data, dict), f"{filename} should be valid JSON dict"

    def test_ise_bundle_contracts_marked_required(self):
        """Test that institutional contracts are marked as required in manifest."""
        with tempfile.TemporaryDirectory() as tmpdir:
            result = compile_bundle(
                idl=MINIMAL_IDL,
                bundle_name="test-bundle",
                output_dir=tmpdir,
                validate_finance_pilot=True,
            )

            assert result.success

            manifest_path = Path(tmpdir) / "test-bundle" / "bundle.manifest.json"
            with open(manifest_path) as f:
                manifest = json.load(f)

            # Find institutional contracts in manifest
            institutional = {"policies.json", "mandates.json", "autonomy.json"}
            for contract in manifest["contracts"]:
                if contract["file"] in institutional:
                    assert contract["required"] is True, \
                        f"{contract['file']} should be marked as required"

    def test_ise_bundle_hash_format(self):
        """Test that ISE generates hashes in SHA256: prefix format."""
        with tempfile.TemporaryDirectory() as tmpdir:
            result = compile_bundle(
                idl=MINIMAL_IDL,
                bundle_name="test-bundle",
                output_dir=tmpdir,
                validate_finance_pilot=True,
            )

            assert result.success

            manifest_path = Path(tmpdir) / "test-bundle" / "bundle.manifest.json"
            with open(manifest_path) as f:
                manifest = json.load(f)

            for contract in manifest["contracts"]:
                sha256 = contract["sha256"]
                assert sha256.startswith("SHA256:"), \
                    f"Hash should start with SHA256: prefix, got: {sha256}"
                # Verify it's valid hex after prefix
                hex_part = sha256[7:]
                assert len(hex_part) == 64, f"Hash should be 64 hex chars, got {len(hex_part)}"
                assert all(c in "0123456789abcdef" for c in hex_part), \
                    f"Hash should be hex, got: {hex_part}"

    def test_ise_bundle_hash_verification(self):
        """Test that ISE-generated hashes match actual file contents."""
        with tempfile.TemporaryDirectory() as tmpdir:
            result = compile_bundle(
                idl=MINIMAL_IDL,
                bundle_name="test-bundle",
                output_dir=tmpdir,
                validate_finance_pilot=True,
            )

            assert result.success

            bundle_path = Path(tmpdir) / "test-bundle"
            manifest_path = bundle_path / "bundle.manifest.json"
            with open(manifest_path) as f:
                manifest = json.load(f)

            for contract in manifest["contracts"]:
                if contract["file"] == "bundle.manifest.json":
                    continue  # Skip manifest itself

                file_path = bundle_path / contract["file"]
                if file_path.exists():
                    assert verify_contract_hash(file_path, contract["sha256"]), \
                        f"Hash mismatch for {contract['file']}"

    def test_ise_bundle_loads_in_loader(self):
        """Test that ISE-generated bundle loads successfully in runtime loader."""
        with tempfile.TemporaryDirectory() as tmpdir:
            result = compile_bundle(
                idl=MINIMAL_IDL,
                bundle_name="test-bundle",
                output_dir=tmpdir,
                validate_finance_pilot=True,
            )

            assert result.success, f"Compilation failed: {result.error_message}"

            bundle_path = Path(tmpdir) / "test-bundle"

            # Set environment to use our bundle
            os.environ["ENGINE_BUNDLE_PATH"] = str(bundle_path)

            try:
                # Load the bundle
                load_bundle()

                # Should NOT be in safe mode
                assert not runtime_state.is_safe_mode(), \
                    f"Loader entered SAFE_MODE: {runtime_state.reason_code} - {runtime_state.details}"
            finally:
                os.environ.pop("ENGINE_BUNDLE_PATH", None)

    def test_ise_bundle_all_required_contracts_present(self):
        """Test that all required contracts from REQUIRED_CONTRACTS are emitted."""
        with tempfile.TemporaryDirectory() as tmpdir:
            result = compile_bundle(
                idl=MINIMAL_IDL,
                bundle_name="test-bundle",
                output_dir=tmpdir,
                validate_finance_pilot=True,
            )

            assert result.success

            bundle_path = Path(tmpdir) / "test-bundle"

            # Check all required contracts exist
            for contract_name in REQUIRED_CONTRACTS:
                assert (bundle_path / contract_name).exists(), \
                    f"Required contract {contract_name} should exist"


